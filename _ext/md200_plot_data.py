# Sphinx extension: packs the MD200 test CSV files into JavaScript files loaded by the interactive
# plots (_static/md200/*_plot.html). The CSV files stay the only data source; the generated .js
# files only let the plots work without a web server (browsers block fetching files from disk).
import json
import os

DATASETS = ('inductive_load', 'dynamometer')


def pack(app):
    root = os.path.join(app.srcdir, '_static', 'md200')
    for name in DATASETS:
        data = {}
        base = os.path.join(root, name)
        for folder, _, files in sorted(os.walk(base)):
            for f in sorted(files):
                if f.endswith('.csv'):
                    path = os.path.join(folder, f)
                    with open(path, encoding='utf-8-sig') as fp:
                        data[os.path.relpath(path, root).replace(os.sep, '/')] = fp.read()
        with open(os.path.join(root, name + '_data.js'), 'w') as fp:
            fp.write('/* generated by _ext/md200_plot_data.py from the CSV files - do not edit */\n')
            fp.write('var MD200_CSV = ' + json.dumps(data) + ';\n')


def setup(app):
    app.connect('builder-inited', pack)
    return {'parallel_read_safe': True}
